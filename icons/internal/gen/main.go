// Command gen writes an icon library's Go package from the library's own
// release: a variable for each icon, holding it as parsed, so that a program
// is linked with only the icons it names and reads them without parsing, and a package beside it that lists
// them all for looking one up by name.
//
//	go run ./icons/internal/gen -lib lucide
//
// The release is fetched from GitHub at the version below; to move a
// library on, change its version here and run the command again.
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"
	"unicode"

	"github.com/ironpark/ggui/ui/icons"
)

// A variant is one directory of a release: every SVG in it is an icon,
// named as its file is with the suffix after it.
type variant struct{ dir, suffix string }

type library struct {
	repo, version string
	variants      []variant
}

var libraries = map[string]library{
	"lucide": {"lucide-icons/lucide", "1.73.0", []variant{{"icons", ""}}},
	"tabler": {"tabler/tabler-icons", "v3.51.0", []variant{{"icons/outline", ""}, {"icons/filled", "-filled"}}},
	// The sources as drawn, not the optimized ones: see the package's README.
	"heroicons": {"tailwindlabs/heroicons", "v2.2.0", []variant{{"src/24/outline", ""}, {"src/24/solid", "-solid"}}},
}

type glyph struct{ name, ident, data string }

func main() {
	name := flag.String("lib", "", "the library to write: lucide, tabler or heroicons")
	out := flag.String("out", "", "the package's directory (default icons/<lib>)")
	flag.Parse()
	lib, ok := libraries[*name]
	if !ok {
		log.Fatalf("gen: no library %q", *name)
	}
	if *out == "" {
		*out = filepath.Join("icons", *name)
	}
	glyphs, err := read(lib)
	if err != nil {
		log.Fatalf("gen: %v", err)
	}
	if err := write(*name, lib, glyphs, *out); err != nil {
		log.Fatalf("gen: %v", err)
	}
	log.Printf("gen: %s %s, %d icons in %s", *name, lib.version, len(glyphs), *out)
}

// read fetches the release and returns its icons in name order.
func read(lib library) ([]glyph, error) {
	url := "https://codeload.github.com/" + lib.repo + "/tar.gz/refs/tags/" + lib.version
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	zr, err := gzip.NewReader(resp.Body)
	if err != nil {
		return nil, err
	}
	var glyphs []glyph
	idents := map[string]string{}
	for tr := tar.NewReader(zr); ; {
		h, err := tr.Next()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, err
		}
		// The archive's files are under one directory named after the tag.
		_, file, _ := strings.Cut(h.Name, "/")
		if h.Typeflag != tar.TypeReg || path.Ext(file) != ".svg" {
			continue
		}
		for _, v := range lib.variants {
			if path.Dir(file) != v.dir {
				continue
			}
			data, err := io.ReadAll(tr)
			if err != nil {
				return nil, err
			}
			g := glyph{name: strings.TrimSuffix(path.Base(file), ".svg") + v.suffix}
			g.ident = ident(g.name)
			if other, taken := idents[g.ident]; taken {
				return nil, fmt.Errorf("%s and %s are both %s", other, g.name, g.ident)
			}
			idents[g.ident] = g.name
			// What is kept is the icon as parsed, not its source: smaller,
			// and read without parsing.
			parsed, err := icons.Parse(data)
			if err != nil {
				return nil, fmt.Errorf("%s: %v", file, err)
			}
			bin, err := parsed.MarshalBinary()
			if err != nil {
				return nil, fmt.Errorf("%s: %v", file, err)
			}
			if _, err := icons.ParseBinary(bin); err != nil {
				return nil, fmt.Errorf("%s: %v", file, err)
			}
			g.data = string(bin)
			glyphs = append(glyphs, g)
		}
	}
	if len(glyphs) == 0 {
		return nil, fmt.Errorf("no icons under %v of %s", lib.variants, url)
	}
	sort.Slice(glyphs, func(i, j int) bool { return glyphs[i].name < glyphs[j].name })
	return glyphs, nil
}

// reserved are the names the packages declare themselves.
var reserved = map[string]bool{"Set": true, "Version": true}

// ident is the Go name of an icon: "arrow-down" is ArrowDown. A name that
// starts with a digit, or is one the package uses, has Icon before it.
func ident(name string) string {
	var b strings.Builder
	up := true
	for _, r := range name {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			up = true
			continue
		}
		if up {
			r = unicode.ToUpper(r)
		}
		b.WriteRune(r)
		up = false
	}
	id := b.String()
	if id == "" || unicode.IsDigit(rune(id[0])) || reserved[id] {
		id = "Icon" + id
	}
	return id
}

const header = "// Code generated by icons/internal/gen from %s %s. DO NOT EDIT.\n\n"

func write(name string, lib library, glyphs []glyph, dir string) error {
	old, _ := filepath.Glob(filepath.Join(dir, "glyphs*.go"))
	for _, f := range old {
		if err := os.Remove(f); err != nil {
			return err
		}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, header, lib.repo, lib.version)
	fmt.Fprintf(&b, "package %s\n\n", name)
	fmt.Fprintf(&b, "// Version is the %s release the icons are from.\nconst Version = %q\n", lib.repo, strings.TrimPrefix(lib.version, "v"))
	if err := source(filepath.Join(dir, "glyphs.go"), b.Bytes()); err != nil {
		return err
	}
	// The icons, a file for each first letter so that none is unwieldy.
	files := map[byte]*bytes.Buffer{}
	var keys []byte
	for _, g := range glyphs {
		k := g.name[0]
		if k >= '0' && k <= '9' {
			k = '0'
		}
		f := files[k]
		if f == nil {
			f = &bytes.Buffer{}
			files[k] = f
			keys = append(keys, k)
			fmt.Fprintf(f, header, lib.repo, lib.version)
			fmt.Fprintf(f, "package %s\n\nimport \"github.com/ironpark/ggui/ui/icons\"\n\nvar (\n", name)
		}
		fmt.Fprintf(f, "\t%s = &icons.Glyph{Name: %q, Data: %q}\n", g.ident, g.name, g.data)
	}
	for _, k := range keys {
		files[k].WriteString(")\n")
		if err := source(filepath.Join(dir, "glyphs_"+string(k)+".go"), files[k].Bytes()); err != nil {
			return err
		}
	}
	// Every icon in name order, for a lookup by name.
	b.Reset()
	fmt.Fprintf(&b, header, lib.repo, lib.version)
	fmt.Fprintf(&b, "package all\n\nimport (\n\t\"github.com/ironpark/ggui/icons/%s\"\n\t\"github.com/ironpark/ggui/ui/icons\"\n)\n\n", name)
	b.WriteString("var glyphs = [...]*icons.Glyph{\n")
	for _, g := range glyphs {
		fmt.Fprintf(&b, "\t%s.%s,\n", name, g.ident)
	}
	b.WriteString("}\n")
	return source(filepath.Join(dir, "all", "glyphs.go"), b.Bytes())
}

// source writes a Go file as gofmt would have it.
func source(file string, src []byte) error {
	out, err := format.Source(src)
	if err != nil {
		return fmt.Errorf("%s: %v", file, err)
	}
	if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
		return err
	}
	return os.WriteFile(file, out, 0o644)
}
